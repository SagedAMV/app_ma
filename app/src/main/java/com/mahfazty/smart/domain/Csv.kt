package com.mahfazty.smart.domain

/**
 * مولد CSV متوافق مع RFC 4180 وExcel — عزل منطق جدول التصدير عن المستودعات والواجهات.
 *
 * سبب عيب «الجدول ينشاء خطأ بالكامل» (v2.8.2 وما قبله): كل مصدِّر كان يبني الصفوف
 * بالتركيب النصي المباشر "${...},${...}" بلا أي اقتباس، وعمود المبلغ يستخدم
 * Money.fmtLat الذي يضيف فواصل تجميع ("23,000") فتنشطر الخلية إلى عمودين إضافيين،
 * وأي ملاحظة تحوي سطراً جديداً تكسر الصف وتزيح كل الصفوف بعده.
 * ثبت على ملف المستخدم الحقيقي (474 عملية): 194 صفًا منشطر الأعمدة (41%)
 * + صف مكسور بملاحظة تحوي \n ('بيع دبب بترول (حافز من منير)\nتبقي ').
 *
 * القواعد هنا (RFC 4180):
 *  - الخلية تُقتبس فقط عند الحاجة (فاصلة / اقتباس / LF / CR) — بلا اقتباس زائد
 *  - الاقتباس الداخلي يُهرَّب بـ "" (الضِعف)
 *  - الصف ينتهي بـ \n دائمًا (Excel يفهم \n وحدها، و\r\n تظهر كمحارف زائدة في بعض الأدوات)
 *  - المبالغ عبر Money.csvAmount: بلا فواصل تجميع إطلاقًا
 *  - BOM يبقى أول الملف لكي يقرأ Excel العربي UTF-8 بشكل صحيح
 */
object Csv {

    /** BOM — Excel يعرض العربية الصحيحة من UTF-8 فقط معه */
    const val BOM = "\uFEFF"

    /** خلية واحدة آمنة: اقتباس فقط عند الحاجة، وتهريب " بـ "" */
    fun field(value: String?): String {
        val v = value ?: ""
        val needsQuoting = v.any { it == ',' || it == '"' || it == '\n' || it == '\r' }
        return if (needsQuoting) "\"" + v.replace("\"", "\"\"") + "\"" else v
    }

    /** صف كامل: خلايا مفصولة بفواصل وينتهي بـ \n */
    fun row(vararg cells: String?): String =
        cells.joinToString(",") { field(it) } + "\n"

    /** رقم بلا كسور زائدة: 5.0 → "5" و 2.5 → "2.5" (للمواد: الكميات والأسعار) */
    fun num(n: Double): String =
        if (!n.isInfinite() && n == kotlin.math.floor(n)) n.toLong().toString() else n.toString()
}
